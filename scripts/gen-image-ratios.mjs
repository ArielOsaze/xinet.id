#!/usr/bin/env node
/**
 * Generates src/lib/image-ratios.ts from the real files in public/products.
 *
 * WHY THIS EXISTS
 *
 * Product captures are drawn inside a fixed-ratio frame. If the frame's ratio
 * does not match the capture's, `object-contain` leaves empty bars and the card
 * reads as a cut-off or broken screenshot; LumaWall's screens are 1.89 to 2.69
 * against a 16:10 frame, so up to 40% of the card was empty.
 *
 * The ratio therefore has to be known before the image loads, otherwise the
 * layout also shifts when it arrives. Reading the files at build time gives both:
 * the frame is correct on the first paint and nothing moves.
 *
 * Dimensions are parsed straight from the WebP headers so this stays dependency
 * free and runs anywhere Node does, including the deploy build.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "public", "products");
const out = join(root, "src", "lib", "image-ratios.ts");

/** Width and height from a WebP buffer, for all three chunk flavours. */
function webpSize(buf) {
  if (buf.length < 30) return null;
  if (buf.toString("ascii", 0, 4) !== "RIFF") return null;
  if (buf.toString("ascii", 8, 12) !== "WEBP") return null;

  let p = 12;
  while (p + 8 <= buf.length) {
    const fourcc = buf.toString("ascii", p, p + 4);
    const size = buf.readUInt32LE(p + 4);
    const d = p + 8;

    if (fourcc === "VP8X") {
      // Canvas size, stored as 24-bit little-endian minus one.
      const w = 1 + (buf[d + 4] | (buf[d + 5] << 8) | (buf[d + 6] << 16));
      const h = 1 + (buf[d + 7] | (buf[d + 8] << 8) | (buf[d + 9] << 16));
      return { w, h };
    }
    if (fourcc === "VP8 ") {
      // Lossy: 14-bit width/height after the 3-byte start code and 3-byte tag.
      const w = buf.readUInt16LE(d + 6) & 0x3fff;
      const h = buf.readUInt16LE(d + 8) & 0x3fff;
      return { w, h };
    }
    if (fourcc === "VP8L") {
      // Lossless: signature byte, then 14 bits each, packed little-endian.
      const b0 = buf[d + 1], b1 = buf[d + 2], b2 = buf[d + 3], b3 = buf[d + 4];
      const bits = b0 | (b1 << 8) | (b2 << 16) | (b3 << 24);
      return { w: 1 + (bits & 0x3fff), h: 1 + ((bits >> 14) & 0x3fff) };
    }
    p = d + size + (size % 2); // chunks are padded to even sizes
  }
  return null;
}

const files = readdirSync(dir).filter((f) => f.toLowerCase().endsWith(".webp")).sort();
const entries = [];
for (const f of files) {
  const size = webpSize(readFileSync(join(dir, f)));
  if (!size) {
    console.error(`  ! could not read dimensions: ${f}`);
    continue;
  }
  entries.push([`/products/${f}`, +(size.w / size.h).toFixed(4), size.w, size.h]);
}

const body = entries
  .map(([p, r, w, h]) => `  "${p}": { ratio: ${r}, width: ${w}, height: ${h} },`)
  .join("\n");

const file = `// GENERATED by scripts/gen-image-ratios.mjs — do not edit by hand.
// Run \`node scripts/gen-image-ratios.mjs\` (or any build) to refresh.
//
// The real pixel size of every product capture, read from the files themselves.
// Frames use \`ratio\` so a capture fits exactly: no empty bars, no cropping, and
// no layout shift while the image loads.

export type ImageSize = { ratio: number; width: number; height: number };

export const IMAGE_SIZES: Record<string, ImageSize> = {
${body}
};

/** Size of a capture, or undefined if it is not a known product image. */
export function imageSize(src: string): ImageSize | undefined {
  return IMAGE_SIZES[src];
}

/** Frame ratio for a capture, falling back to 16:10 for unknown images. */
export function frameRatio(src: string): number {
  return IMAGE_SIZES[src]?.ratio ?? 16 / 10;
}
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, file);
console.log(`  wrote ${entries.length} image ratios to src/lib/image-ratios.ts`);
for (const [p, r, w, h] of entries) console.log(`    ${p.padEnd(42)} ${w}x${h}  ratio ${r}`);
